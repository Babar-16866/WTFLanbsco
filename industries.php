(function () {
  const board = document.querySelector('[data-ind-board]');
  if (!board) return;
  const rows = board.querySelectorAll('.ind-row');
  const parts = board.querySelectorAll('.ind-preview [data-i]');
  const show = (i) => {
    rows.forEach((r) => r.classList.toggle('is-active', r.dataset.i === i));
    parts.forEach((p) => p.classList.toggle('is-active', p.dataset.i === i));
  };
  let scrollingUntil = 0;
  rows.forEach((r) => {
    r.addEventListener('pointermove', () => {
      if (performance.now() < scrollingUntil) return;
      if (!r.classList.contains('is-active')) show(r.dataset.i);
    });
    r.addEventListener('focusin', () => show(r.dataset.i));
  });
  const desk = window.matchMedia('(min-width: 901px)');
  let ticking = false;
  const onScroll = () => {
    ticking = false;
    if (!desk.matches) return;
    const b = board.getBoundingClientRect();
    const f = board.querySelector('.ind-preview').getBoundingClientRect();
    const total = b.height - f.height;
    const p = total > 0 ? Math.min(0.999, Math.max(0, (f.top - b.top) / total)) : 0;
    const pick = rows[Math.floor(p * rows.length)];
    if (!pick.classList.contains('is-active')) show(pick.dataset.i);
  };
  window.addEventListener('scroll', () => {
    scrollingUntil = performance.now() + 250;
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(onScroll);
  }, { passive: true });
  onScroll();
})();
</script>

