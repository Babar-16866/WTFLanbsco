      <article class="legal-content insight-article reveal" id="plumbing-google-ads">
        <p class="insight-meta">Plumbing · 7 min read</p>
        <h2 class="insight-title">Google Ads for Plumbing Companies</h2>
        <p>Plumbing is one of the most competitive categories in Google Ads, so wasted clicks add up fast. The companies that win don't just spend more - they structure campaigns so every dollar goes toward the jobs they actually want.</p>

        <h3>Split emergency and planned work</h3>
        <p>Emergency searches ("burst pipe," "emergency plumber near me") behave differently from planned ones ("water heater replacement," "repipe cost"). Give each its own campaign with its own budget, ad copy, and schedule so one doesn't eat the other.</p>

        <h3>Run Local Services Ads alongside Search</h3>
        <p>Local Services Ads sit at the top of the page and charge per lead instead of per click. They work well for plumbing, but they aren't a replacement for Search - running both gives you more of the page.</p>

        <h3>Negative keywords save real money</h3>
        <ul>
          <li>DIY terms: "how to," "fix it yourself," "parts"</li>
          <li>Job seekers: "jobs," "salary," "apprentice," "license"</li>
          <li>Services you don't offer, and cities you don't serve</li>
        </ul>

        <h3>Send clicks to a matching landing page</h3>
        <p>An ad for water heater installation should land on a water heater page, not your homepage. Match the headline, show a tappable number, and add reviews that mention that exact job.</p>

        <h3>Track booked jobs, not clicks</h3>
        <p>Use call tracking and connect your booking software if you can. Cost per click tells you very little; cost per booked job tells you whether the campaign is making money.</p>
