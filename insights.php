        <p class="insight-meta">Pool Services · 6 min read</p>
        <h2 class="insight-title">Local SEO for Pool Companies</h2>
        <p>Pool companies live and die by route density. Local SEO is the most cost-effective way to add accounts in the neighborhoods you already service - if you set it up with that goal in mind.</p>

        <h3>Get your Google Business Profile right</h3>
        <ul>
          <li>Choose the most accurate primary category, then add secondary ones for repairs and equipment</li>
          <li>Set a service area that matches your real routes</li>
          <li>Upload photos every month - clean pools, equipment installs, your trucks</li>
          <li>Post seasonal updates for openings, closings, and repair specials</li>
        </ul>

        <h3>Build pages for services and neighborhoods</h3>
        <p>One page for weekly cleaning, one for green pool cleanup, one for pump and filter repair, one for heaters. Then add pages for the main areas you serve, with real details about each one.</p>

        <h3>Make reviews part of the route</h3>
        <p>Ask happy weekly customers for a review with a photo. Reviews that mention the neighborhood and the service help both rankings and conversions.</p>

        <h3>Keep your listings consistent</h3>
        <p>Your name, address, and phone number should match everywhere - Google, Yelp, Apple Maps, Facebook, and local directories. Small mismatches make it harder for Google to trust your listing.</p>
